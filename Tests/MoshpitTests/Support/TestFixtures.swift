import Foundation

/// The checked-in captures under `Tests/MoshpitTests/Fixtures/`.
///
/// They used to be read straight from the checkout through `#filePath` — the
/// absolute path of the source file on the Mac that compiled the tests. A
/// simulator shares that filesystem, so it worked there; a real iPhone or
/// iPad has no such path, and every test reading a fixture failed on device.
///
/// The folder now ships inside the test bundle as a folder reference
/// (`project.yml`), keeping its layout, and is read from there. The source
/// tree stays the fallback for a run whose bundle predates that — a Mac or
/// simulator run of a project generated by an older `project.yml`.
enum TestFixtures {
    /// Anchors `Bundle(for:)` to the test bundle.
    private final class BundleToken {}

    /// The fixture folder inside the test bundle, if it shipped there.
    static var bundledRoot: URL? {
        Bundle(for: BundleToken.self).resourceURL?
            .appendingPathComponent("Fixtures", isDirectory: true)
    }

    /// The fixture folder in the checkout this file was compiled from.
    static var sourceRoot: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()   // …/MoshpitTests/Support
            .deletingLastPathComponent()   // …/MoshpitTests
            .appendingPathComponent("Fixtures", isDirectory: true)
    }

    /// `Fixtures/<relativePath>`: the bundled copy when there is one, the
    /// source tree's otherwise.
    static func url(_ relativePath: String) -> URL {
        if let bundled = bundledRoot?.appendingPathComponent(relativePath),
           FileManager.default.fileExists(atPath: bundled.path) {
            return bundled
        }
        return sourceRoot.appendingPathComponent(relativePath)
    }

    static func data(_ relativePath: String) throws -> Data {
        try Data(contentsOf: url(relativePath))
    }

    static func string(_ relativePath: String) throws -> String {
        try String(contentsOf: url(relativePath), encoding: .utf8)
    }
}
