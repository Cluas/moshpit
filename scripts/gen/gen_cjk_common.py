#!/usr/bin/env python3
"""Generate Moshpit/UI/Terminal/Core/CoreTermCommonCJK.swift: the CJK glyphs the
core view's atlas draws ahead of time (CoreTermAtlas.prewarmCommon).

The Chinese characters are GB2312's, most frequent first, by the frequency
order Mozilla's universal charset detector measured (chardet's
gb2312freq.py, LGPL-2.1: "512 -> 0.79, 1024 -> 0.92" of running text); the
atlas takes as many as it is set to (CoreTermCommonCJK.hanziWarmed). The rest
are every wide CJK symbol and punctuation mark, the full-width forms, and the
kana.

Usage: gen_cjk_common.py [path/to/gb2312freq.py]
(default: the one of an installed chardet, or pip's vendored copy)
"""
import os
import sys

OUT = os.path.join(os.path.dirname(__file__), "..", "..",
                   "Moshpit", "UI", "Terminal", "Core", "CoreTermCommonCJK.swift")


def table_path():
    if len(sys.argv) > 1:
        return sys.argv[1]
    for mod in ("chardet.gb2312freq", "pip._vendor.chardet.gb2312freq"):
        try:
            m = __import__(mod, fromlist=["x"])
            return m.__file__
        except ImportError:
            continue
    sys.exit("no gb2312freq.py: pass its path")


def hanzi():
    ns = {}
    exec(open(table_path(), encoding="utf-8").read(), ns)
    order = ns["GB2312_CHAR_TO_FREQ_ORDER"]
    # The table's index: GB2312 from 0xB0A1, 94 to a row (chardet's
    # GB2312DistributionAnalysis.get_order).
    ranked = sorted(range(len(order)), key=lambda i: order[i])
    out = []
    for i in ranked:
        try:
            out.append(bytes([0xB0 + i // 94, 0xA1 + i % 94]).decode("gb2312"))
        except UnicodeDecodeError:
            continue  # a code point GB2312 leaves empty
    return "".join(out)


def span(lo, hi, skip=()):
    return "".join(chr(c) for c in range(lo, hi + 1) if c not in skip)


def main():
    han = hanzi()
    # Wide (two cells): CJK symbols and punctuation (not the ideographic
    # space, which draws nothing, nor the combining tone marks), the
    # full-width forms, the kana.
    wide = (span(0x3001, 0x303F, skip=range(0x302A, 0x3030))
            + span(0xFF01, 0xFF60) + span(0xFFE0, 0xFFE6)
            + span(0x3041, 0x3096) + span(0x30A1, 0x30FA) + "ー")
    # Narrow (one cell, East Asian ambiguous): what Chinese text uses most.
    narrow = "…—·“”‘’"
    swift = f'''// Generated by scripts/gen/gen_cjk_common.py. Do not edit.

/// The CJK glyphs an atlas draws ahead of time (``CoreTermAtlas``'s
/// common prewarm): the most frequent Chinese characters (GB2312's
/// {len(han)}, most frequent first, by Mozilla's frequency order: the first
/// 1000 are about 91% of running text), the wide CJK symbols and
/// punctuation, the full-width forms and the kana, and the narrow
/// punctuation Chinese text uses most.
enum CoreTermCommonCJK {{
    /// How many of ``hanzi`` an atlas warms: all of them. A screen of
    /// Chinese has hundreds of different characters, and with only the
    /// first 1000 warmed a first screen still rasterised the rest at once
    /// (141 ms of the main thread at -Onone, 51 at -O on an iPad mini;
    /// 16.7 with all, for a 2048 px atlas instead of 1024:
    /// TERMINAL-VIEW.md §5.7).
    static let hanziWarmed = hanzi.count
    /// Chinese, most frequent first; two cells wide (atlas style 4).
    static let hanzi = "{han}"
    /// The other wide ones (style 4).
    static let wide = "{wide}"
    /// One cell (style 0).
    static let narrow = "{narrow}"
}}
'''
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(swift)
    print(f"{OUT}: {len(han)} hanzi, {len(wide)} other wide, {len(narrow)} narrow")


main()
