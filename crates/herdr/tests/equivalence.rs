//! The Rust port against the Swift implementation's recorded output,
//! without swiftc: each `*.swift.txt` next to a corpus is what
//! `harness/swift/main.swift` printed for it over the app's unchanged
//! sources (`harness/equivalence.py update-goldens`; both left with the
//! Swift herdr code, E1, so the recordings are final: at cf25626b). The base corpus (every
//! Swift test's inputs, the app's captures, Foundation's edges) and the
//! recorded one (live herdr 0.9.5) must print the same on both sides. Every
//! divergence fixture must print its recorded fix here and something else
//! (or a trap) on the Swift side, and every fix in `harness/divergences.json`
//! must have one (buffer-cap's input was generated by equivalence.py).

use std::collections::BTreeSet;
use std::fs;

use moshpit_herdr::harness;
use moshpit_herdr::json;

fn read(name: &str) -> String {
    let path = format!(
        "{}/tests/fixtures/corpus/{name}",
        env!("CARGO_MANIFEST_DIR")
    );
    fs::read_to_string(&path).unwrap_or_else(|error| panic!("{path}: {error}"))
}

fn lines(text: &str) -> Vec<&str> {
    text.lines().filter(|line| !line.is_empty()).collect()
}

fn cases(text: &str) -> Vec<&str> {
    text.lines()
        .filter(|line| !line.trim().is_empty() && !line.starts_with('#'))
        .collect()
}

/// A harness string literal back to its value.
fn unquote(literal: &str) -> String {
    let body = &literal[1..literal.len() - 1];
    let mut out = String::new();
    let mut chars = body.chars();
    while let Some(c) = chars.next() {
        if c != '\\' {
            out.push(c);
            continue;
        }
        match chars.next() {
            Some(escaped @ ('"' | '\\')) => out.push(escaped),
            Some('u') => {
                let hex: String = chars.by_ref().skip(1).take_while(|&c| c != '}').collect();
                out.push(char::from_u32(u32::from_str_radix(&hex, 16).unwrap()).unwrap());
            }
            other => panic!("bad escape {other:?} in {literal}"),
        }
    }
    out
}

/// The string tokens of a JSON text, as written.
fn string_tokens(text: &str) -> Vec<String> {
    let mut tokens = Vec::new();
    let bytes = text.as_bytes();
    let mut at = 0;
    while at < bytes.len() {
        if bytes[at] == b'"' {
            let start = at;
            at += 1;
            while bytes[at] != b'"' {
                at += if bytes[at] == b'\\' { 2 } else { 1 };
            }
            tokens.push(text[start..=at].to_owned());
        }
        at += 1;
    }
    tokens.sort();
    tokens
}

/// Swift's JSONEncoder writes a request's keys in a random order: request
/// lines agree when they are the same JSON with the same string tokens.
fn same(case: &str, swift: &str, rust: &str) -> bool {
    if swift == rust {
        return true;
    }
    let kind = case.split(' ').next().unwrap_or("");
    if kind != "request" && kind != "subscribe" {
        return false;
    }
    let (Some((_, swift)), Some((_, rust))) = (swift.split_once(' '), rust.split_once(' ')) else {
        return false;
    };
    let (swift, rust) = (unquote(swift), unquote(rust));
    json::parse(swift.as_bytes()) == json::parse(rust.as_bytes())
        && json::parse(rust.as_bytes()).is_some()
        && string_tokens(&swift) == string_tokens(&rust)
}

fn check_corpus(name: &str) {
    let corpus = read(&format!("{name}.txt"));
    let swift = read(&format!("{name}.swift.txt"));
    let cases = cases(&corpus);
    let swift = lines(&swift);
    let rust = harness::run_corpus(&corpus);
    assert_eq!(rust.len(), cases.len());
    assert_eq!(swift.len(), cases.len(), "{name}.swift.txt is stale");
    let mut different = Vec::new();
    for ((case, swift), rust) in cases.iter().zip(&swift).zip(&rust) {
        if !same(case, swift, rust) {
            different.push(format!(
                "{}\n    swift {}\n    rust  {}",
                &case[..case.len().min(120)],
                &swift[..swift.len().min(200)],
                &rust[..rust.len().min(200)]
            ));
        }
    }
    assert!(
        different.is_empty(),
        "{} of {} {name} cases differ from Swift:\n{}",
        different.len(),
        cases.len(),
        different.join("\n")
    );
}

#[test]
fn the_base_corpus_prints_what_the_swift_code_prints() {
    check_corpus("base");
}

#[test]
fn the_recorded_corpus_prints_what_the_swift_code_prints() {
    check_corpus("recorded");
}

#[test]
fn every_divergence_fixture_prints_its_fix_and_not_the_swift_behaviour() {
    let corpus = read("divergences.txt");
    let entries: Vec<(&str, &str)> = lines(&corpus)
        .iter()
        .map(|line| line.split_once(' ').expect("`<id> <case>`"))
        .collect();
    let plain: String = entries
        .iter()
        .map(|(_, case)| format!("{case}\n"))
        .collect();
    let rust = harness::run_corpus(&plain);
    let recorded = read("divergences.rust.txt");
    let swift = read("divergences.swift.txt");
    let (recorded, swift) = (lines(&recorded), lines(&swift));
    assert_eq!(rust.len(), entries.len());
    for (index, (id, case)) in entries.iter().enumerate() {
        assert_eq!(rust[index], recorded[index], "{id}: {case}");
        assert!(
            !same(case, swift[index], &rust[index]),
            "{id}: the Swift code prints the fix too: {case}"
        );
    }
}

#[test]
fn every_fix_is_documented_and_has_a_fixture() {
    let ledger = json::parse_object(read("../../../harness/divergences.json").as_bytes())
        .expect("divergences.json parses");
    let fixes: BTreeSet<String> = ledger
        .objects("fixes")
        .expect("fixes")
        .iter()
        .map(|fix| fix.str("id").expect("id").to_owned())
        .collect();
    let corpus = read("divergences.txt");
    let covered: BTreeSet<String> = lines(&corpus)
        .iter()
        .map(|line| line.split(' ').next().unwrap().to_owned())
        .collect();
    assert!(
        covered.is_subset(&fixes),
        "fixtures for undocumented fixes: {:?}",
        covered.difference(&fixes)
    );
    let missing: Vec<&String> = fixes
        .iter()
        .filter(|fix| !covered.contains(*fix) && fix.as_str() != "buffer-cap")
        .collect();
    assert!(missing.is_empty(), "fixes without a fixture: {missing:?}");
}
