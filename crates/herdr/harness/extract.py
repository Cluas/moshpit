#!/usr/bin/env python3
"""Copy declarations out of app sources the harness cannot compile whole.

    extract.py <out.swift>

SessionHub.swift (UIKit, SwiftTerm, Citadel) holds two pure statics the
frame channel's input goes through, `herdrPaste` and `arrowKeyName`, and
TmuxSessionController.swift holds `AgentHook`, which HerdrSnapshot.swift
builds. Each is copied verbatim, line for line, from the signature line to
the line that closes it (it must close at the signature's own
indentation); the two functions go inside `enum SessionHubExtract`. Fails
when a signature is missing or not unique, so a rename can't leave the
harness testing stale code.
"""
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))


def block(path, signature):
    lines = open(os.path.join(REPO, path), encoding="utf-8").read().split("\n")
    starts = [i for i, line in enumerate(lines) if signature in line]
    if len(starts) != 1:
        sys.exit(f"extract.py: {signature!r} found {len(starts)} times in {path}")
    start = starts[0]
    indent = lines[start][: len(lines[start]) - len(lines[start].lstrip())]
    depth = 0
    for end in range(start, len(lines)):
        depth += lines[end].count("{") - lines[end].count("}")
        if depth == 0 and end > start:
            if lines[end] != indent + "}":
                sys.exit(f"extract.py: {signature!r} in {path} does not close at its indentation")
            return lines[start : end + 1], start + 1
    sys.exit(f"extract.py: {signature!r} in {path} never closes")


def main():
    out = [
        "// Generated by crates/herdr/harness/extract.py: verbatim copies of app",
        "// declarations whose files the harness cannot compile. Do not edit.",
        "import Foundation",
        "",
    ]
    hub = "Moshpit/Services/SessionHub.swift"
    out.append("enum SessionHubExtract {")
    for signature in ("nonisolated static func herdrPaste(", "static func arrowKeyName("):
        lines, number = block(hub, signature)
        out.append(f"    // {hub}:{number}")
        out.extend(lines)
    out.append("}")
    out.append("")
    controller = "Moshpit/Services/Tmux/TmuxSessionController.swift"
    lines, number = block(controller, "struct AgentHook: Equatable, Sendable {")
    out.append(f"// {controller}:{number}")
    out.extend(lines)
    open(sys.argv[1], "w", encoding="utf-8").write("\n".join(out) + "\n")


main()
