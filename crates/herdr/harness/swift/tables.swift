// Prints, as ranges of scalars, the characters on which Swift's Character
// semantics and this crate's byte semantics can disagree, for the fuzz
// tagger (harness/fuzz.py, divergence `unicode-syntax`, `quote-unicode`,
// `canonical-equivalence`, `refusal-cut`). Run by harness/equivalence.py
// tables; the output is committed as harness/unicode-hazards.txt.
//
// A scalar is a hazard when it can share a grapheme cluster with an ASCII
// neighbour or with itself (combining and spacing marks, ZWJ, variation
// selectors, prepended concatenation marks, regional indicators, Hangul
// jamo), when it is not its own NFC form or has a nonzero combining class
// (Swift compares and hashes strings by canonical equivalence, which only
// differs from byte equality for strings that are not NFC), when it is
// canonically equivalent to an ASCII character
// (U+037E is `;`), or when it is a non-ASCII numeral (Character.isNumber).

import Foundation

func hazard(_ scalar: Unicode.Scalar) -> Bool {
    if scalar.value < 0x80 { return false }
    var after = "a"; after.unicodeScalars.append(scalar)
    var before = ""; before.unicodeScalars.append(scalar); before += "a"
    var twice = ""; twice.unicodeScalars.append(scalar); twice.unicodeScalars.append(scalar)
    if after.count == 1 || before.count == 1 || twice.count == 1 { return true }
    if (0x1100...0x11FF).contains(scalar.value) || (0xA960...0xA97F).contains(scalar.value)
        || (0xD7B0...0xD7FF).contains(scalar.value) { return true }
    // Not its own NFC (a singleton such as U+212B ANGSTROM SIGN): two NFC
    // strings are canonically equivalent only when they are equal.
    let alone = String(scalar)
    if alone.precomposedStringWithCanonicalMapping.unicodeScalars.elementsEqual(alone.unicodeScalars) == false {
        return true
    }
    if scalar.properties.canonicalCombiningClass != .notReordered { return true }
    if Character(scalar).isNumber { return true }
    for ascii in 0x20..<0x7F where alone == String(UnicodeScalar(UInt8(ascii))) { return true }
    return false
}

var out: [String] = []
var start: UInt32?
var last: UInt32 = 0
for value in UInt32(0x80)...0x10FFFF {
    guard let scalar = Unicode.Scalar(value) else {
        if let open = start { out.append(open == last ? String(open, radix: 16) : "\(String(open, radix: 16))-\(String(last, radix: 16))"); start = nil }
        continue
    }
    if hazard(scalar) {
        if start == nil { start = value }
        last = value
    } else if let open = start {
        out.append(open == last ? String(open, radix: 16) : "\(String(open, radix: 16))-\(String(last, radix: 16))")
        start = nil
    }
}
if let open = start { out.append(open == last ? String(open, radix: 16) : "\(String(open, radix: 16))-\(String(last, radix: 16))") }
print("# Generated by harness/swift/tables.swift on macOS \(ProcessInfo.processInfo.operatingSystemVersionString). Do not edit.")
for chunk in stride(from: 0, to: out.count, by: 12) {
    print(out[chunk..<min(chunk + 12, out.count)].joined(separator: " "))
}
